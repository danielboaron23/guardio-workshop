// Generates dist/tokens.css (Tailwind v4 @theme) from src/index.ts.
// Run from the repo root: pnpm tokens
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { color, radius, fontFamily, text } from '../src/index.ts';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const px = (n: number) => `${n}px`;

const lines: string[] = [];
for (const [k, v] of Object.entries(color)) lines.push(`  --color-${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(radius)) lines.push(`  --radius-${k}: ${px(v)};`);
lines.push(`  --font-sans: "${fontFamily.sans}", ui-sans-serif, system-ui, sans-serif;`);
for (const [k, v] of Object.entries(text)) {
  lines.push(`  --text-${k}: ${px(v.size)};`);
  lines.push(`  --text-${k}--line-height: ${px(v.lineHeight)};`);
  lines.push(`  --text-${k}--font-weight: ${v.weight};`);
}

// spacing: Tailwind's default 4px base already matches Figma (p-4 = 16px), so no override.
const css = `/* Generated by packages/tokens/scripts/build-css.ts — do not edit by hand. */\n@theme {\n${lines.join('\n')}\n}\n`;

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist', 'tokens.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css written (${lines.length} vars) → ${out}`);
